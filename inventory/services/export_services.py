class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to compute dynamic total page count and draw standard headers/footers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#475569"))

        # Header
        self.drawString(54, 750, "SHOPSENSE ENTERPRISE ANALYTICS")
        self.setFont("Helvetica", 8)
        self.drawRightString(612 - 54, 750, timezone.now().strftime("%Y-%m-%d %H:%M:%S UTC"))
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(54, 742, 612 - 54, 742)

        # Footer
        self.line(54, 45, 612 - 54, 45)
        self.drawString(54, 32, "Confidential — Generated by ShopSense BI Engine")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 54, 32, page_str)
        self.restoreState()


