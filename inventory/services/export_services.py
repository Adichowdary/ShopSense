    @classmethod
    def _build_kpi_cards(cls, kpis: List[tuple[str, str]], styles: Dict[str, ParagraphStyle]) -> Table:
        """Render horizontal cards for executive KPIs."""
        labels = [Paragraph(k[0], styles['KpiLabel']) for k in kpis]
        values = [Paragraph(k[1], styles['KpiValue']) for k in kpis]
        data = [values, labels]

        col_width = (612 - 108) / len(kpis)
        table = Table(data, colWidths=[col_width] * len(kpis))
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ]))
        return table

    @classmethod
    def _build_table(cls, headers: List[str], rows: List[List[Any]], col_widths: Optional[List[float]] = None) -> Table:
        styles = cls._get_styles()
        header_p = [Paragraph(h, styles['TableHeader']) for h in headers]
        table_data = [header_p]

        for row in rows:
            formatted_row = []
            for cell in row:
                if isinstance(cell, Paragraph):
                    formatted_row.append(cell)
                else:
                    formatted_row.append(Paragraph(str(cell), styles['TableCell']))
            table_data.append(formatted_row)

        table = Table(table_data, colWidths=col_widths, repeatRows=1)
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1E293B')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F8FAFC')]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
            ('LEFTPADDING', (0, 0), (-1, -1), 6),
            ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ]))
        return table

