def resolve_db_host(hostname):
    """Resolve database host with fallback to resilient IP if DNS temporarily fails."""
    if not hostname or hostname in ('localhost', '127.0.0.1'):
        return hostname
    try:
        import socket
        socket.gethostbyname(hostname)
        return hostname
    except Exception:
        if 'supabase.com' in hostname:
            return '65.0.195.55'
        return hostname


